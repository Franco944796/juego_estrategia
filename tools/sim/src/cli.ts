import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { defaultConfig } from '@si/config';
import { renderReport, simulateSeason } from './simulate';

const { values } = parseArgs({
  options: {
    bots: { type: 'string', default: String(defaultConfig.demo.bots + 1) },
    seed: { type: 'string', default: '1' },
    runs: { type: 'string', default: '5' },
    write: { type: 'boolean', default: false },
  },
});

const bots = Number(values.bots);
const seed = Number(values.seed);
const runs = Number(values.runs);
const results = Array.from({ length: runs }, (_, i) => simulateSeason(defaultConfig, seed + i, bots));
const header = `## Latest run\n\n\`pnpm sim --bots ${bots} --seed ${seed} --runs ${runs}\`: ${runs} seasons of ${defaultConfig.season.durationMin} game minutes, all lords bots, means over the runs.`;
const report = renderReport(results, header);
console.log(report);

if (values.write) {
  const path = fileURLToPath(new URL('../../../docs/BALANCE.md', import.meta.url));
  const previous = existsSync(path) ? readFileSync(path, 'utf8') : '';
  const marker = '## Tuning log';
  const log = previous.includes(marker)
    ? previous.slice(previous.indexOf(marker))
    : `${marker}\n\nNo changes yet.\n`;
  const intro = '# Balance\n\nGenerated by `tools/sim`; the tuning log below is kept between runs.\n';
  writeFileSync(path, `${intro}\n${report}\n${log}`);
  console.log(`wrote ${path}`);
}
