import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { defaultConfig, liveConfig } from '@si/config';
import { renderReport, simulateSeason, TARGETS } from './simulate';

const { values } = parseArgs({
  options: {
    preset: { type: 'string', default: 'demo' },
    bots: { type: 'string', default: String(defaultConfig.demo.bots + 1) },
    seed: { type: 'string', default: '1' },
    runs: { type: 'string' },
    write: { type: 'boolean', default: false },
  },
});

const preset = values.preset === 'live' ? 'live' : 'demo';
const config = preset === 'live' ? liveConfig : defaultConfig;
const bots = Number(values.bots);
const seed = Number(values.seed);
// Short demo seasons vary a lot from seed to seed; a month-long live season takes ~35 s to simulate.
const DEFAULT_RUNS = { demo: 12, live: 3 };
const runs = Number(values.runs ?? DEFAULT_RUNS[preset]);
const results = Array.from({ length: runs }, (_, i) => simulateSeason(config, seed + i, bots));
const command = `pnpm sim --preset ${preset} --bots ${bots} --seed ${seed} --runs ${runs}`;
const title = preset === 'live' ? 'Live preset (online world)' : 'Demo preset';
const header = `## ${title}\n\n\`${command}\`: ${runs} seasons of ${config.season.durationMin} game minutes, all lords bots, means over the runs.`;
const report = renderReport(results, header, TARGETS[preset]);
console.log(report);

if (values.write) {
  const path = fileURLToPath(new URL('../../../docs/BALANCE.md', import.meta.url));
  const previous = existsSync(path) ? readFileSync(path, 'utf8') : '';
  const sections = new Map<string, string>();
  for (const name of ['demo', 'live']) {
    const open = `<!-- sim:${name} -->`;
    const close = `<!-- /sim:${name} -->`;
    const from = previous.indexOf(open);
    const to = previous.indexOf(close);
    if (from >= 0 && to > from) sections.set(name, previous.slice(from + open.length, to).trim());
  }
  sections.set(preset, report.trim());
  const marker = '## Tuning log';
  const log = previous.includes(marker)
    ? previous.slice(previous.indexOf(marker))
    : `${marker}\n\nNo changes yet.\n`;
  const body = ['demo', 'live']
    .filter((name) => sections.has(name))
    .map((name) => `<!-- sim:${name} -->\n\n${sections.get(name) ?? ''}\n\n<!-- /sim:${name} -->`)
    .join('\n\n');
  const intro =
    '# Balance\n\nGenerated by `tools/sim`; each preset section is rewritten by its own run and the tuning log is kept.\n';
  writeFileSync(path, `${intro}\n${body}\n\n${log}`);
  console.log(`wrote ${path}`);
}
